export function formatINR(amount: number): string {
  return '₹' + amount.toLocaleString('en-IN');
}

export function computeCompatibilityScore(
  user: LifestyleVector,
  candidate: LifestyleVector
): number {
  let score = 62;
  if (user.sleepSchedule === candidate.sleepSchedule) score += 12;
  else if (
    user.sleepSchedule === 'Balanced' ||
    candidate.sleepSchedule === 'Balanced'
  ) {
    score += 6;
  }
  if (user.diet === candidate.diet) score += 10;
  else if (user.diet !== 'Flexible' && candidate.diet === 'Eggetarian') {
    score += 5;
  }
  if (user.smoking === candidate.smoking) score += 8;
  if (user.workSetup === candidate.workSetup) score += 5;
  else score += 2;
  if (user.petFriendly === candidate.petFriendly) score += 3;
  return Math.min(99, score);
}
